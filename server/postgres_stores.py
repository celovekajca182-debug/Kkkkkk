"""PostgreSQL-backed account and chat history stores for durable SWIN deployments."""
from __future__ import annotations

import hashlib
import secrets
import time
from typing import Any

from auth import TOKEN_TTL_SECONDS, digest_token, hash_password, normalize_email, validate_email, verify_password


def _connect(database_url: str):
    if not database_url.startswith(("postgres://", "postgresql://")):
        raise ValueError("DATABASE_URL must be a PostgreSQL connection URL.")
    import psycopg
    from psycopg.rows import dict_row

    return psycopg.connect(database_url, row_factory=dict_row, connect_timeout=15)


class PostgresAuthStore:
    """PostgreSQL equivalent of AuthStore; password and bearer tokens remain hashed."""

    def __init__(self, database_url: str):
        self.database_url = database_url
        self._initialize()

    def _initialize(self) -> None:
        with _connect(self.database_url) as db:
            db.execute(
                """
                CREATE TABLE IF NOT EXISTS users (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    email TEXT NOT NULL UNIQUE,
                    password_hash TEXT NOT NULL,
                    created_at BIGINT NOT NULL
                )
                """
            )
            db.execute(
                """
                CREATE TABLE IF NOT EXISTS auth_tokens (
                    token_hash TEXT PRIMARY KEY,
                    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                    expires_at BIGINT NOT NULL,
                    created_at BIGINT NOT NULL
                )
                """
            )
            db.execute(
                "CREATE INDEX IF NOT EXISTS idx_auth_tokens_user_id ON auth_tokens(user_id)"
            )
            db.execute(
                "CREATE INDEX IF NOT EXISTS idx_auth_tokens_expiry ON auth_tokens(expires_at)"
            )

    def create_user(self, email: str, password: str) -> dict[str, Any]:
        normalized = validate_email(email)
        encoded = hash_password(password)
        now = int(time.time())
        try:
            with _connect(self.database_url) as db:
                row = db.execute(
                    """
                    INSERT INTO users(email, password_hash, created_at)
                    VALUES (%s, %s, %s)
                    RETURNING id, email
                    """,
                    (normalized, encoded, now),
                ).fetchone()
            return {"id": int(row["id"]), "email": row["email"]}
        except Exception as error:
            try:
                from psycopg.errors import UniqueViolation
            except ImportError:
                raise
            if isinstance(error, UniqueViolation):
                raise ValueError("Аккаунт с такой почтой уже существует.") from error
            raise

    def authenticate(self, email: str, password: str) -> dict[str, Any] | None:
        normalized = normalize_email(email)
        with _connect(self.database_url) as db:
            row = db.execute(
                "SELECT id, email, password_hash FROM users WHERE lower(email) = %s",
                (normalized,),
            ).fetchone()
        if row is None or not verify_password(password, row["password_hash"]):
            return None
        return {"id": int(row["id"]), "email": row["email"]}

    def issue_token(self, user_id: int) -> tuple[str, int]:
        token = secrets.token_urlsafe(36)
        now = int(time.time())
        expires_at = now + TOKEN_TTL_SECONDS
        with _connect(self.database_url) as db:
            db.execute(
                """
                INSERT INTO auth_tokens(token_hash, user_id, expires_at, created_at)
                VALUES (%s, %s, %s, %s)
                """,
                (digest_token(token), int(user_id), expires_at, now),
            )
            db.execute("DELETE FROM auth_tokens WHERE expires_at <= %s", (now,))
        return token, expires_at

    def user_for_token(self, token: str) -> dict[str, Any] | None:
        if not token or len(token) > 256:
            return None
        now = int(time.time())
        with _connect(self.database_url) as db:
            row = db.execute(
                """
                SELECT users.id, users.email
                FROM auth_tokens
                JOIN users ON users.id = auth_tokens.user_id
                WHERE auth_tokens.token_hash = %s AND auth_tokens.expires_at > %s
                """,
                (digest_token(token), now),
            ).fetchone()
        if row is None:
            return None
        return {"id": int(row["id"]), "email": row["email"]}

    def revoke_token(self, token: str) -> None:
        if not token:
            return
        with _connect(self.database_url) as db:
            db.execute(
                "DELETE FROM auth_tokens WHERE token_hash = %s",
                (digest_token(token),),
            )


class PostgresChatHistoryStore:
    """PostgreSQL chat history, isolated by account and client session."""

    def __init__(self, database_url: str, max_messages_per_session: int = 400):
        self.database_url = database_url
        self.max_messages_per_session = max(20, int(max_messages_per_session))
        self._initialize()

    def _initialize(self) -> None:
        with _connect(self.database_url) as db:
            db.execute(
                """
                CREATE TABLE IF NOT EXISTS chat_messages (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                    session_id TEXT NOT NULL,
                    role TEXT NOT NULL CHECK(role IN ('user', 'assistant')),
                    content TEXT NOT NULL,
                    created_at BIGINT NOT NULL
                )
                """
            )
            db.execute(
                """
                CREATE INDEX IF NOT EXISTS idx_chat_messages_session
                ON chat_messages(user_id, session_id, id)
                """
            )

    def save_turn(
        self, user_id: int, session_id: str, user_message: str, assistant_message: str
    ) -> None:
        now = int(time.time())
        with _connect(self.database_url) as db:
            with db.cursor() as cursor:
                cursor.executemany(
                    """
                    INSERT INTO chat_messages(user_id, session_id, role, content, created_at)
                    VALUES (%s, %s, %s, %s, %s)
                    """,
                    (
                        (int(user_id), session_id, "user", user_message[:120000], now),
                        (int(user_id), session_id, "assistant", assistant_message[:120000], now),
                    ),
                )
            db.execute(
                """
                DELETE FROM chat_messages
                WHERE user_id = %s AND session_id = %s
                  AND id NOT IN (
                    SELECT id FROM chat_messages
                    WHERE user_id = %s AND session_id = %s
                    ORDER BY id DESC LIMIT %s
                  )
                """,
                (
                    int(user_id),
                    session_id,
                    int(user_id),
                    session_id,
                    self.max_messages_per_session,
                ),
            )

    def messages(
        self, user_id: int, session_id: str, limit: int = 80
    ) -> list[dict[str, Any]]:
        safe_limit = max(2, min(int(limit), self.max_messages_per_session))
        with _connect(self.database_url) as db:
            rows = db.execute(
                """
                SELECT role, content, created_at
                FROM chat_messages
                WHERE user_id = %s AND session_id = %s
                ORDER BY id DESC LIMIT %s
                """,
                (int(user_id), session_id, safe_limit),
            ).fetchall()
        return [
            {
                "role": row["role"],
                "content": row["content"],
                "created_at": int(row["created_at"]),
            }
            for row in reversed(rows)
        ]

    def turns(
        self, user_id: int, session_id: str, limit: int = 6
    ) -> list[tuple[str, str]]:
        rows = self.messages(user_id, session_id, limit=max(2, min(limit * 2, 24)))
        turns: list[tuple[str, str]] = []
        pending_user: str | None = None
        for row in rows:
            if row["role"] == "user":
                pending_user = row["content"]
            elif row["role"] == "assistant" and pending_user is not None:
                turns.append((pending_user, row["content"]))
                pending_user = None
        return turns[-max(1, int(limit)):]

    def restore_messages(
        self, user_id: int, session_id: str, messages: list[dict[str, str]]
    ) -> bool:
        normalized = [
            (item.get("role", ""), item.get("content", "").strip())
            for item in messages
            if item.get("role") in {"user", "assistant"}
            and item.get("content", "").strip()
        ][-self.max_messages_per_session:]
        if not normalized:
            return False
        now = int(time.time())
        with _connect(self.database_url) as db:
            existing = db.execute(
                """
                SELECT 1 FROM chat_messages
                WHERE user_id = %s AND session_id = %s LIMIT 1
                """,
                (int(user_id), session_id),
            ).fetchone()
            if existing is not None:
                return False
            with db.cursor() as cursor:
                cursor.executemany(
                    """
                    INSERT INTO chat_messages(user_id, session_id, role, content, created_at)
                    VALUES (%s, %s, %s, %s, %s)
                    """,
                    [
                        (int(user_id), session_id, role, content[:120000], now)
                        for role, content in normalized
                    ],
                )
        return True

    def clear(self, user_id: int, session_id: str) -> int:
        with _connect(self.database_url) as db:
            cursor = db.execute(
                "DELETE FROM chat_messages WHERE user_id = %s AND session_id = %s",
                (int(user_id), session_id),
            )
            return int(cursor.rowcount)
