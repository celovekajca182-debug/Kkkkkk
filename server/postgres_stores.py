"""PostgreSQL-backed account and chat history stores for durable SWIN deployments."""
from __future__ import annotations

import hashlib
import secrets
import sqlite3
import time
from pathlib import Path
from typing import Any

from auth import TOKEN_TTL_SECONDS, digest_token, hash_password, normalize_email, validate_email, verify_password


def _connect(database_url: str):
    if not database_url.startswith(("postgres://", "postgresql://")):
        raise ValueError("DATABASE_URL must be a PostgreSQL connection URL.")
    import psycopg
    from psycopg.rows import dict_row

    return psycopg.connect(database_url, row_factory=dict_row, connect_timeout=15)


class PostgresAuthStore:
    """PostgreSQL equivalent of AuthStore; password and bearer tokens remain hashed."""

    def __init__(self, database_url: str):
        self.database_url = database_url
        self._initialize()

    def _initialize(self) -> None:
        with _connect(self.database_url) as db:
            db.execute(
                """
                CREATE TABLE IF NOT EXISTS users (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    email TEXT NOT NULL UNIQUE,
                    password_hash TEXT NOT NULL,
                    created_at BIGINT NOT NULL
                )
                """
            )
            db.execute(
                """
                CREATE TABLE IF NOT EXISTS auth_tokens (
                    token_hash TEXT PRIMARY KEY,
                    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                    expires_at BIGINT NOT NULL,
                    created_at BIGINT NOT NULL
                )
                """
            )
            db.execute(
                "CREATE INDEX IF NOT EXISTS idx_auth_tokens_user_id ON auth_tokens(user_id)"
            )
            db.execute(
                "CREATE INDEX IF NOT EXISTS idx_auth_tokens_expiry ON auth_tokens(expires_at)"
            )

    def create_user(self, email: str, password: str) -> dict[str, Any]:
        normalized = validate_email(email)
        encoded = hash_password(password)
        now = int(time.time())
        try:
            with _connect(self.database_url) as db:
                row = db.execute(
                    """
                    INSERT INTO users(email, password_hash, created_at)
                    VALUES (%s, %s, %s)
                    RETURNING id, email
                    """,
                    (normalized, encoded, now),
                ).fetchone()
            return {"id": int(row["id"]), "email": row["email"]}
        except Exception as error:
            try:
                from psycopg.errors import UniqueViolation
            except ImportError:
                raise
            if isinstance(error, UniqueViolation):
                raise ValueError("Аккаунт с такой почтой уже существует.") from error
            raise

    def authenticate(self, email: str, password: str) -> dict[str, Any] | None:
        normalized = normalize_email(email)
        with _connect(self.database_url) as db:
            row = db.execute(
                "SELECT id, email, password_hash FROM users WHERE lower(email) = %s",
                (normalized,),
            ).fetchone()
        if row is None or not verify_password(password, row["password_hash"]):
            return None
        return {"id": int(row["id"]), "email": row["email"]}

    def issue_token(self, user_id: int) -> tuple[str, int]:
        token = secrets.token_urlsafe(36)
        now = int(time.time())
        expires_at = now + TOKEN_TTL_SECONDS
        with _connect(self.database_url) as db:
            db.execute(
                """
                INSERT INTO auth_tokens(token_hash, user_id, expires_at, created_at)
                VALUES (%s, %s, %s, %s)
                """,
                (digest_token(token), int(user_id), expires_at, now),
            )
            db.execute("DELETE FROM auth_tokens WHERE expires_at <= %s", (now,))
        return token, expires_at

    def user_for_token(self, token: str) -> dict[str, Any] | None:
        if not token or len(token) > 256:
            return None
        now = int(time.time())
        with _connect(self.database_url) as db:
            row = db.execute(
                """
                SELECT users.id, users.email
                FROM auth_tokens
                JOIN users ON users.id = auth_tokens.user_id
                WHERE auth_tokens.token_hash = %s AND auth_tokens.expires_at > %s
                """,
                (digest_token(token), now),
            ).fetchone()
        if row is None:
            return None
        return {"id": int(row["id"]), "email": row["email"]}

    def revoke_token(self, token: str) -> None:
        if not token:
            return
        with _connect(self.database_url) as db:
            db.execute(
                "DELETE FROM auth_tokens WHERE token_hash = %s",
                (digest_token(token),),
            )


class PostgresChatHistoryStore:
    """PostgreSQL chat history, isolated by account and client session."""

    def __init__(self, database_url: str, max_messages_per_session: int = 400):
        self.database_url = database_url
        self.max_messages_per_session = max(20, int(max_messages_per_session))
        self._initialize()

    def _initialize(self) -> None:
        with _connect(self.database_url) as db:
            db.execute(
                """
                CREATE TABLE IF NOT EXISTS chat_messages (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                    session_id TEXT NOT NULL,
                    role TEXT NOT NULL CHECK(role IN ('user', 'assistant')),
                    content TEXT NOT NULL,
                    created_at BIGINT NOT NULL
                )
                """
            )
            db.execute(
                """
                CREATE INDEX IF NOT EXISTS idx_chat_messages_session
                ON chat_messages(user_id, session_id, id)
                """
            )

    def save_turn(
        self, user_id: int, session_id: str, user_message: str, assistant_message: str
    ) -> None:
        now = int(time.time())
        with _connect(self.database_url) as db:
            with db.cursor() as cursor:
                cursor.executemany(
                    """
                    INSERT INTO chat_messages(user_id, session_id, role, content, created_at)
                    VALUES (%s, %s, %s, %s, %s)
                    """,
                    (
                        (int(user_id), session_id, "user", user_message[:120000], now),
                        (int(user_id), session_id, "assistant", assistant_message[:120000], now),
                    ),
                )
            db.execute(
                """
                DELETE FROM chat_messages
                WHERE user_id = %s AND session_id = %s
                  AND id NOT IN (
                    SELECT id FROM chat_messages
                    WHERE user_id = %s AND session_id = %s
                    ORDER BY id DESC LIMIT %s
                  )
                """,
                (
                    int(user_id),
                    session_id,
                    int(user_id),
                    session_id,
                    self.max_messages_per_session,
                ),
            )

    def messages(
        self, user_id: int, session_id: str, limit: int = 80
    ) -> list[dict[str, Any]]:
        safe_limit = max(2, min(int(limit), self.max_messages_per_session))
        with _connect(self.database_url) as db:
            rows = db.execute(
                """
                SELECT role, content, created_at
                FROM chat_messages
                WHERE user_id = %s AND session_id = %s
                ORDER BY id DESC LIMIT %s
                """,
                (int(user_id), session_id, safe_limit),
            ).fetchall()
        return [
            {
                "role": row["role"],
                "content": row["content"],
                "created_at": int(row["created_at"]),
            }
            for row in reversed(rows)
        ]

    def turns(
        self, user_id: int, session_id: str, limit: int = 6
    ) -> list[tuple[str, str]]:
        rows = self.messages(user_id, session_id, limit=max(2, min(limit * 2, 24)))
        turns: list[tuple[str, str]] = []
        pending_user: str | None = None
        for row in rows:
            if row["role"] == "user":
                pending_user = row["content"]
            elif row["role"] == "assistant" and pending_user is not None:
                turns.append((pending_user, row["content"]))
                pending_user = None
        return turns[-max(1, int(limit)):]

    def restore_messages(
        self, user_id: int, session_id: str, messages: list[dict[str, str]]
    ) -> bool:
        normalized = [
            (item.get("role", ""), item.get("content", "").strip())
            for item in messages
            if item.get("role") in {"user", "assistant"}
            and item.get("content", "").strip()
        ][-self.max_messages_per_session:]
        if not normalized:
            return False
        now = int(time.time())
        with _connect(self.database_url) as db:
            existing = db.execute(
                """
                SELECT 1 FROM chat_messages
                WHERE user_id = %s AND session_id = %s LIMIT 1
                """,
                (int(user_id), session_id),
            ).fetchone()
            if existing is not None:
                return False
            with db.cursor() as cursor:
                cursor.executemany(
                    """
                    INSERT INTO chat_messages(user_id, session_id, role, content, created_at)
                    VALUES (%s, %s, %s, %s, %s)
                    """,
                    [
                        (int(user_id), session_id, role, content[:120000], now)
                        for role, content in normalized
                    ],
                )
        return True

    def clear(self, user_id: int, session_id: str) -> int:
        with _connect(self.database_url) as db:
            cursor = db.execute(
                "DELETE FROM chat_messages WHERE user_id = %s AND session_id = %s",
                (int(user_id), session_id),
            )
            return int(cursor.rowcount)


def migrate_sqlite_to_postgres(sqlite_path: str | Path, database_url: str) -> dict[str, int]:
    """Copy existing SQLite identities, sessions, and chat history once.

    A marker is written in the same PostgreSQL transaction as the copy, so
    retries after a process restart do not duplicate conversation messages.
    User IDs are mapped by normalized email to preserve account ownership.
    """
    source_path = Path(sqlite_path)
    if not source_path.is_file():
        return {"users": 0, "tokens": 0, "messages": 0}

    source = sqlite3.connect(str(source_path), timeout=15)
    source.row_factory = sqlite3.Row
    try:
        try:
            old_users = source.execute(
                "SELECT id, email, password_hash, created_at FROM users ORDER BY id"
            ).fetchall()
        except sqlite3.OperationalError:
            old_users = []
        try:
            old_tokens = source.execute(
                "SELECT token_hash, user_id, expires_at, created_at FROM auth_tokens"
            ).fetchall()
        except sqlite3.OperationalError:
            old_tokens = []
        try:
            old_messages = source.execute(
                """
                SELECT id, user_id, session_id, role, content, created_at
                FROM chat_messages ORDER BY id
                """
            ).fetchall()
        except sqlite3.OperationalError:
            old_messages = []
    finally:
        source.close()

    copied_users = copied_tokens = copied_messages = 0
    with _connect(database_url) as db:
        db.execute(
            """
            CREATE TABLE IF NOT EXISTS swin_migration_log (
                migration_key TEXT PRIMARY KEY,
                applied_at BIGINT NOT NULL
            )
            """
        )
        already_done = db.execute(
            "SELECT 1 FROM swin_migration_log WHERE migration_key = %s",
            ("sqlite-legacy-v1",),
        ).fetchone()
        if already_done is not None:
            return {"users": 0, "tokens": 0, "messages": 0}

        user_id_map: dict[int, int] = {}
        for row in old_users:
            email = str(row["email"]).strip().lower()
            db.execute(
                """
                INSERT INTO users(id, email, password_hash, created_at)
                VALUES (%s, %s, %s, %s)
                ON CONFLICT (email) DO NOTHING
                """,
                (int(row["id"]), email, row["password_hash"], int(row["created_at"])),
            )
            current = db.execute(
                "SELECT id FROM users WHERE lower(email) = %s",
                (email,),
            ).fetchone()
            if current is None:
                raise RuntimeError("Не удалось сопоставить старый аккаунт PostgreSQL.")
            user_id_map[int(row["id"])] = int(current["id"])
            copied_users += 1

        for row in old_tokens:
            mapped_user_id = user_id_map.get(int(row["user_id"]))
            if mapped_user_id is None:
                continue
            cursor = db.execute(
                """
                INSERT INTO auth_tokens(token_hash, user_id, expires_at, created_at)
                VALUES (%s, %s, %s, %s)
                ON CONFLICT (token_hash) DO NOTHING
                """,
                (
                    row["token_hash"],
                    mapped_user_id,
                    int(row["expires_at"]),
                    int(row["created_at"]),
                ),
            )
            copied_tokens += max(0, cursor.rowcount)

        for row in old_messages:
            mapped_user_id = user_id_map.get(int(row["user_id"]))
            if mapped_user_id is None:
                continue
            db.execute(
                """
                INSERT INTO chat_messages(id, user_id, session_id, role, content, created_at)
                VALUES (%s, %s, %s, %s, %s, %s)
                ON CONFLICT (id) DO NOTHING
                """,
                (
                    int(row["id"]),
                    mapped_user_id,
                    row["session_id"],
                    row["role"],
                    row["content"],
                    int(row["created_at"]),
                ),
            )
            copied_messages += 1

        # Explicitly inserted identity values must advance the sequences.
        db.execute(
            """
            SELECT setval(
                pg_get_serial_sequence('users', 'id'),
                COALESCE(MAX(id), 1),
                MAX(id) IS NOT NULL
            ) FROM users
            """
        )
        db.execute(
            """
            SELECT setval(
                pg_get_serial_sequence('chat_messages', 'id'),
                COALESCE(MAX(id), 1),
                MAX(id) IS NOT NULL
            ) FROM chat_messages
            """
        )
        db.execute(
            "INSERT INTO swin_migration_log(migration_key, applied_at) VALUES (%s, %s)",
            ("sqlite-legacy-v1", int(time.time())),
        )

    return {
        "users": copied_users,
        "tokens": copied_tokens,
        "messages": copied_messages,
    }
